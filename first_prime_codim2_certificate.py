# ---------- exact rational LDL^T ----------

def exact_ldl_positive(RSTR, shift):
    n = len(RSTR)
    R = [[Fraction(s) for s in row] for row in RSTR]
    D = []
    LM = [[Fraction(0) for _ in range(n)] for __ in range(n)]
    for i in range(n):
        LM[i][i] = Fraction(1)

    for j in range(n):
        dj = R[j][j] - shift
        for k in range(j):
            dj -= LM[j][k]*LM[j][k]*D[k]

        assert dj > 0, f"Exact LDL pivot {j} nonpositive: {dj}"
        D.append(dj)

        for i in range(j+1,n):
            x = R[i][j]
            for k in range(j):
                x -= LM[i][k]*LM[j][k]*D[k]
            LM[i][j] = x/dj

    return D


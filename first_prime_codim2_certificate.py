        Pplus[i][j]  = Aplus[i][j]  - BBplus[i][j]/dp
        if i == j:
            Pminus[i][j] -= TAIL_BUDGET_MINUS
            Pplus[i][j]  -= TAIL_BUDGET_PLUS


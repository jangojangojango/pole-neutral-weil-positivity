assert HIGH_B_BOUND < Fraction(409,1000)

# Tail remainder operator norm:
# epsilon_n <= 9/(100 n^3), ||R|| <= 4*pi*epsilon_21.
R_OP = 4*PI*aq(Fraction(9,100))/arb(21**3)

# Deliberately coarse diagonal remainder: 14/(5 n^2).
DIAG_REM = aq(Fraction(14,5) + Fraction(1,36))/arb(21**2)

ODD_TAIL_LB = (
    (arb(21)/L).log()
    - PI/2
    - LOG2/SQRT2
    - DIAG_REM
    - R_OP
)
EVEN_TAIL_LB = (
    (arb(21)/L).log()
    - LOG2/SQRT2
    - DIAG_REM
    - R_OP
)

print("Certified odd raw-tail lower bracket  =", ODD_TAIL_LB)
print("Certified even raw-tail lower bracket =", EVEN_TAIL_LB)

D_MINUS = Fraction(22,25)
D_PLUS  = Fraction(49,20)

assert ODD_TAIL_LB > aq(D_MINUS)
assert EVEN_TAIL_LB > aq(D_PLUS)

# ---------- precompute mathfrak b_n ----------

CUTOFF = 10000
print("Computing rigorous mathfrak_b_n balls, n=1,...,", CUTOFF)

BSEQ = [None]*(CUTOFF+1)
for n in range(1,CUTOFF+1):
    BSEQ[n] = mathfrak_b(n)
    if n <= 20:
        assert frac_abs_lt(BSEQ[n], Fraction(2,5))
    if n % 1000 == 0:
        print("  reached n =", n)

# ---------- corrected non-pole parity matrices ----------

def complex_nonpole_diag(n):
    """
    B(V_n,V_n) with pole removed.
    At L=log(3), the k=3 term vanishes and only k=2 is effective.
    """
    prime_diag = SQRT2*LOG2*(1-LOG2/L)*(arb(n)*THETA).cos()
    return dinf_ball(n) - prime_diag

def odd_diag(n):
    return complex_nonpole_diag(n) - BSEQ[n]/arb(n)

def even_diag(n):
    return complex_nonpole_diag(n) + BSEQ[n]/arb(n)

def odd_off(n,m):
    # 2(m b_n - n b_m)/(n^2-m^2)
    return 2*(arb(m)*BSEQ[n]-arb(n)*BSEQ[m]) / arb(n*n-m*m)

def even_off(n,m):
    # 2(n b_n - m b_m)/(n^2-m^2)
    return 2*(arb(n)*BSEQ[n]-arb(m)*BSEQ[m]) / arb(n*n-m*m)

HEAD = list(range(1,21))
NH = 20

Aminus = [[arb(0) for _ in range(NH)] for __ in range(NH)]
Aplus  = [[arb(0) for _ in range(NH)] for __ in range(NH)]

for i,n in enumerate(HEAD):
    for j,m in enumerate(HEAD):
        if n == m:
            Aminus[i][j] = odd_diag(n)
            Aplus[i][j] = even_diag(n)
        else:
            Aminus[i][j] = odd_off(n,m)
            Aplus[i][j] = even_off(n,m)


# first_prime_codim2_certificate.py
#
# Corrected codimension-two certificate at L = log(3).
#
# This script does NOT impose the i/2 condition separately in parity.
# Instead it certifies positivity of the non-pole form B on:
#   (i)  the full odd sector,
#   (ii) the mean-zero even sector.
#
# Then, for a globally constrained f with
#       fhat(0)=fhat(i/2)=0,
# the full pole term in CCM (3.19) vanishes globally and
#       QW(f,f) = B_+(f_+,f_+) + B_-(f_-,f_-).
#
# Requires:
#     python-flint
#
# Source formulas used:
#   CCM arXiv:2511.22755, Lemma 2.3, (3.19), (4.3), (4.4),
#   Proposition 4.3, Proposition 3.4.
#
# RIGOR ARCHITECTURE
# ------------------
# A. Exact rational Taylor/Cauchy input:
#
# r(z) = exp(z/2)/(exp(z)-exp(-z)) - 1/(2z).
#
# On |z|=5/2:
#   |r(z)| < 26/5,
# and log(3)<11/10, hence q:=log(3)/(5/2)<11/25.
#
# For P40, the Taylor polynomial through degree 40,
#
#   |r(x)-P40(x)|
#       <= (26/5)*(11/25)^41/(1-11/25)
#       < 3e-14
#
# on 0<=x<=log(3).
#
# The Taylor coefficients are generated EXACTLY as Fractions, not stored
# as decimal approximations.
#
# B. Analytic tail estimates used by the proof:
#
#   |alpha_n - (1/4-A/n)| < 9/(100 n^3)
#   |d_n^(inf)-log(n/L)| < 14/(5 n^2)
#   0 < A < 1/36
#
# These deliberately coarse rational bounds imply, on n>=21,
#
#   D_- >= 22/25 I = 0.88 I
#   D_+ >= 49/20 I = 2.45 I.
#
# The script rigorously checks the final scalar inequalities with Arb.
#
# C. Head/tail split:
#
# Head modes are n=1,...,20 in both parity sectors.
# For m>10000 we prove analytically
#
#       ||b_m^+||_2, ||b_m^-||_2 < (37/10)/m.
#
# Hence the omitted tail contributes at most
#
#   (37/10)^2 / ((22/25)*10000) I     [odd]
#   (37/10)^2 / ((49/20)*10000) I     [even].
#
# D. Finite certificate:
#
# The script rigorously encloses the two true 20x20 Schur lower-bound
# matrices P_- and P_+ and compares them to fixed exact rational matrices
# R_- and R_+.
#
# It then proves with EXACT Fraction LDL^T:
#
#       R_- - 1/200 I  > 0
#       R_+ - 1/5000 I > 0.
#
# Entrywise tolerances:
#
#       |P_- - R_-|_entry < 1e-4
#       |P_+ - R_+|_entry < 1e-6.
#
# Therefore
#
#   ||P_- - R_-||op <= 20e-4 = .002 < .005,
#   ||P_+ - R_+||op <= 20e-6 = .00002 < .0002,
#
# proving both matrices positive.
#
# IMPORTANT:
# Successful execution certifies the FINITE part of the corrected
# codimension-two reduction.  The accompanying analytic lemmas
# (parity decoupling, form-core transfer, Taylor/Cauchy estimates and
# Schur bridge) are mathematical parts of the proof and should appear
# in the writeup.

from flint import arb, acb, fmpq, ctx
from fractions import Fraction
from math import factorial

ctx.dps = 100

# ---------- exact helpers ----------

def aq(q):
    """Exact rational Fraction -> arb."""
    return arb(fmpq(q.numerator, q.denominator))

def frac_abs_lt(x, q):
    """Rigorous test |arb ball x| < exact rational q."""
    return abs(x) < aq(q)

PI = arb.pi()
L = arb(3).log()
LOG2 = arb(2).log()
SQRT2 = arb(2).sqrt()

KAPPA = LOG2/(PI*SQRT2)
THETA = 2*PI*LOG2/L

# ---------- exact Taylor coefficients of r ----------

def r_taylor_coeffs(N):
    """
    Exact coefficients a_0,...,a_N of
        r(z)=exp(z/2)/(exp(z)-exp(-z))-1/(2z).

    Let S(z)=sinh(z)/z and G(z)=exp(z/2)/(2 S(z)).
    Then z*r(z)=G(z)-1/2.
    Since 2 S G = exp(z/2), the coefficients of G obey an exact
    rational recurrence.
    """
    g = []
    for n in range(N+2):
        val = Fraction(1, 2 * (2**n) * factorial(n))   # e_n / 2
        for j in range(1, n//2 + 1):
            val -= g[n-2*j] / factorial(2*j+1)
        g.append(val)
    return [g[j+1] for j in range(N+1)]

P = r_taylor_coeffs(40)

# Exact Cauchy remainder bound.
R40_Q = Fraction(26,5) * Fraction(11,25)**41 / (1-Fraction(11,25))
assert R40_Q < Fraction(3,10**14)
R40 = aq(R40_Q)

print("Exact P40 remainder bound =", R40)
print("Target: < 3e-14")
assert R40 < arb("3e-14")

# ---------- rigorous trig moments ----------

def real_si(x):
    return acb(x).si().real

def real_ci(x):
    return acb(x).ci().real

def trig_moments(n, max_j):
    """
    I_j = int_0^L x^j sin(kx) dx
    C_j = int_0^L x^j cos(kx) dx
    k=2*pi*n/L, so kL=2*pi*n exactly.
    """
    nA = arb(n)
    k = 2*PI*nA/L
    I = [arb(0)]*(max_j+1)
    C = [arb(0)]*(max_j+1)

    # I_0=C_0=0 at kL=2*pi*n.
    for j in range(1,max_j+1):
        I[j] = -(L**j)/k + arb(j)*C[j-1]/k
        C[j] = -arb(j)*I[j-1]/k
    return I,C

PM1 = arb(0,1)  # rigorous [-1,1]

def alpha_ball(n):
    """
    alpha_L(n) = Si(2*pi*n)/(2*pi)
                 + (1/pi) int_0^L r(x) sin(2*pi*n*x/L) dx.
    """
    I,_ = trig_moments(n,40)
    poly = arb(0)
    for j,pj in enumerate(P):
        poly += aq(pj)*I[j]
    val = real_si(2*PI*arb(n))/(2*PI) + poly/PI
    # |int (r-P40) sin| <= L R40
    return val + PM1*(L*R40/PI)

def dinf_ball(n):
    """
    Non-pole archimedean complex-mode diagonal:
      d_n^(inf)=log(n/L)-Ci(2*pi*n)
                -2 int_0^L (1-x/L) r(x) cos(2*pi*n*x/L) dx.
    """
    _,C = trig_moments(n,41)
    poly = arb(0)
    for j,pj in enumerate(P):
        poly += aq(pj)*(C[j]-C[j+1]/L)
    val = (arb(n)/L).log() - real_ci(2*PI*arb(n)) - 2*poly
    # |1-x/L|<=1.
    return val + PM1*(2*L*R40)

def mathfrak_b(n):
    return alpha_ball(n) + KAPPA*(arb(n)*THETA).sin()

# ---------- low scalar / analytic-tail checks ----------

# A = 1/(4 pi^2) - L(r(0)-r(L))/(2 pi^2)
r0 = aq(Fraction(1,4))
